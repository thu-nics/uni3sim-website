  const missing = new Set();
  function english(value) {
    const raw = String(value), key = raw.trim();
    if (Object.hasOwn(messages, key)) return raw.replace(key, () => messages[key]);
    if (!/[\u3400-\u9fff]/.test(key)) return raw;
    for (const [pattern, replacement] of patterns) {
      if (pattern.test(key)) return raw.replace(key, () => key.replace(pattern, replacement));
    }
    missing.add(key);
    return raw;
  }
  // Also used by the build script to generate a standalone English entry page.
