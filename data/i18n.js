  const t = value => lang === 'en' ? english(value) : String(value);
  const attrs = ['aria-label', 'alt', 'title', 'content'];
  function apply(root) {
    if (lang !== 'en') return root;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {acceptNode(node) {
      return node.parentElement?.closest('script,style,noscript,.language-toggle') ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT;
    }});
    while (walker.nextNode()) walker.currentNode.textContent = t(walker.currentNode.textContent);
    root.querySelectorAll('[aria-label],[alt],[title],meta[content]').forEach(el => {
      if (el.closest('.language-toggle')) return;
      attrs.forEach(attr => {if (el.hasAttribute(attr)) el.setAttribute(attr, t(el.getAttribute(attr)));});
    });
    return root;
  }
  function html(markup) {
    if (lang !== 'en') return markup;
    const template = document.createElement('template');
    template.innerHTML = markup;
    apply(template.content);
    return template.innerHTML;
  }
  const measure = document.createElement('canvas').getContext('2d'), widths = new Map();
  function fitText(value, size, width) {
    if (lang !== 'en' || !width) return size;
    const text = t(value), key = `${size}:${text}`;
    if (!widths.has(key)) {
      measure.font = `${size}px Arial, sans-serif`;
      widths.set(key, measure.measureText(text).width);
    }
    return Number(Math.min(size, size * width / Math.max(1, widths.get(key))).toFixed(2));
  }
